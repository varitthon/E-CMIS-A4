// Screenshots of every step in activity10/playthrough-10x.html (16:9, 1920x1080, main form in focus) — 2026-11-05
// Plan: docs/screen-capture-plan.md
// - steps + case/role come from the playthrough itself (window.PLAYTHROUGH.steps / stepUrl = same as «เปิดหน้า»)
// - one shot set per node; long forms → _01, _02 …; every top-level radio choice → own set (__<branch>); no modals; no typing
// - output: activity10/screenshots/<act>/<node>_<page>[__<branch>]_<NN>.png + .thumb.jpg
//           activity10/screenshots/manifest.js (read by playthrough-10x.html) + index.md + index.xlsx
// Run: node video/tools/capture-screens.js            (all, wipes old shots)
//      node video/tools/capture-screens.js 103.103verdict.v06 | 103 | v06   (re-shoot matching steps, merge manifest)
const path = require("path");
const fs = require("fs");
const { execFileSync } = require("child_process");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..", "..");
const APP = path.join(ROOT, "activity10");
const OUT = path.join(APP, "screenshots");
const MANIFEST = path.join(OUT, "manifest.js");
const VIEWPORT = { width: 1920, height: 1080 };
const THUMB = { width: 480, height: 270 };
const OVERLAP = 80; // px repeated between parts of a long form
const PAD = 12; // px gap above the form card
const MAX_PARTS = 10;
const SETTLE_MS = 450;
/* real screens that are not steps in the playthrough — one plain 16:9 shot each */
const OTHER_PAGES = ["board-report", "dasdbord", "login", "notices", "registry", "search-case", "verdict-form"];
/* pages that open without a case (same list as NO_CASE in the playthrough) */
const NO_CASE = /^(01-work-inbox|02-board-intake|10-3v-00-legal-admin-verdict-intake)\.html$/;

const fileUrl = (rel) => "file:///" + path.join(APP, rel.replace(/^\.\//, "").split("?")[0]).replace(/\\/g, "/") +
  (rel.includes("?") ? "?" + rel.split("?")[1] : "");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const pad2 = (n) => String(n).padStart(2, "0");
const posix = (p) => p.split(path.sep).join("/");

/* filter: one or more keys / prefixes / node ids, comma separated */
function matches(key, filter) {
  if (!filter) return true;
  return filter.split(",").some((f) => key === f || key.startsWith(f + ".") || key.endsWith("." + f));
}

function readManifest() {
  if (!fs.existsSync(MANIFEST)) return {};
  const src = fs.readFileSync(MANIFEST, "utf8");
  const m = src.match(/window\.SHOT_MANIFEST\s*=\s*([\s\S]*);\s*$/);
  return m ? JSON.parse(m[1]) : {};
}

function writeManifest(data) {
  const body = "// generated by video/tools/capture-screens.js — do not edit by hand\n" +
    "window.SHOT_MANIFEST = " + JSON.stringify(data, null, 1) + ";\n";
  fs.writeFileSync(MANIFEST, body, "utf8");
}

function removeShots(entry) {
  (entry && entry.shots ? entry.shots : []).forEach((s) => {
    [s.file, s.thumb].forEach((f) => {
      const p = f && path.join(OUT, f);
      if (p && fs.existsSync(p)) fs.unlinkSync(p);
    });
  });
}

async function launch() {
  try {
    return await chromium.launch({ channel: "chrome", headless: true });
  } catch (e) {
    console.warn("chrome channel not available, using bundled chromium:", e.message.split("\n")[0]);
    return chromium.launch({ headless: true });
  }
}

/* load a page and wait until fonts + scripts settle */
async function load(pg, url) {
  try {
    await pg.goto(url, { waitUntil: "load", timeout: 30000 });
  } catch (e) {
    /* page script navigated away while loading (redirect) → keep whatever page it landed on */
    if (!/ERR_ABORTED/.test(e.message)) throw e;
    await sleep(1500);
    await pg.waitForLoadState("load").catch(() => {});
    console.warn("  redirect:", decodeURI(url).split("/").pop(), "→", decodeURI(pg.url()).split("/").pop());
  }
  await pg.evaluate(() => document.fonts && document.fonts.ready);
  await sleep(SETTLE_MS);
}

/* top-level radio groups of the main form (visible at load, not in sidebar / topbar / modal) */
async function radioGroups(pg) {
  return pg.evaluate(() => {
    const root = document.querySelector(".content") || document.body;
    const blocked = (el) => !!el.closest('[class*="modal"], [role="dialog"], dialog, #sidebar, .sidebar, .topbar');
    const shown = (el) => {
      if (!el) return false;
      const r = el.getBoundingClientRect();
      const s = getComputedStyle(el);
      return r.width > 0 && r.height > 0 && s.visibility !== "hidden" && s.display !== "none";
    };
    const labelOf = (inp) => inp.closest("label") || (inp.id && document.querySelector('label[for="' + CSS.escape(inp.id) + '"]')) || null;
    const groups = new Map();
    root.querySelectorAll('input[type="radio"]').forEach((inp) => {
      if (blocked(inp) || inp.disabled) return;
      const lab = labelOf(inp);
      if (!shown(inp) && !shown(lab)) return;
      const name = inp.name || "#" + inp.id;
      if (!groups.has(name)) groups.set(name, []);
      const text = ((lab && lab.innerText) || (inp.parentElement && inp.parentElement.innerText) || inp.value || "").replace(/\s+/g, " ").trim();
      groups.get(name).push({ value: inp.value || "", label: text.slice(0, 80), checked: inp.checked });
    });
    return Array.from(groups.entries()).map(([name, options]) => ({ name, options }));
  });
}

async function clickRadio(pg, name, index) {
  const ok = await pg.evaluate(({ name, index }) => {
    const root = document.querySelector(".content") || document.body;
    const blocked = (el) => !!el.closest('[class*="modal"], [role="dialog"], dialog, #sidebar, .sidebar, .topbar');
    const list = Array.from(root.querySelectorAll('input[type="radio"]'))
      .filter((i) => (i.name || "#" + i.id) === name && !blocked(i) && !i.disabled);
    const inp = list[index];
    if (!inp) return false;
    document.querySelectorAll("[data-shot-target]").forEach((e) => e.removeAttribute("data-shot-target"));
    const lab = inp.closest("label") || (inp.id && document.querySelector('label[for="' + CSS.escape(inp.id) + '"]'));
    const r = inp.getBoundingClientRect();
    (r.width > 0 && r.height > 0 ? inp : lab || inp).setAttribute("data-shot-target", "1");
    return true;
  }, { name, index });
  if (!ok) return false;
  const target = pg.locator("[data-shot-target]").first();
  await target.scrollIntoViewIfNeeded().catch(() => {});
  await target.click({ force: true, timeout: 3000 }).catch(async () => {
    await pg.evaluate(() => { const el = document.querySelector("[data-shot-target]"); if (el) el.click(); });
  });
  await sleep(250);
  await pg.keyboard.press("Escape"); // close a modal the choice may have opened — modals are not captured
  await sleep(SETTLE_MS);
  return true;
}

/* where the main form starts/ends and which element scrolls it */
async function formGeometry(pg, plain) {
  return pg.evaluate(({ PAD, plain }) => {
    const root = document.querySelector(".content") || document.body;
    const blocked = (el) => !!el.closest('[class*="modal"], [role="dialog"], dialog');
    const shown = (el) => { const r = el.getBoundingClientRect(); return r.width > 0 && r.height > 0 && getComputedStyle(el).visibility !== "hidden"; };
    const cards = plain ? [] : Array.from(root.querySelectorAll(".form-card")).filter((c) => shown(c) && !blocked(c));
    const ends = cards.concat(Array.from(root.querySelectorAll(".form-actions")).filter((c) => shown(c) && !blocked(c)));
    const se = document.scrollingElement || document.documentElement;
    const scrollable = (el) => {
      const s = getComputedStyle(el);
      return /(auto|scroll)/.test(s.overflowY) && el.scrollHeight > el.clientHeight + 2;
    };
    /* a radio click may have scrolled the window or an inner box — start every shot set from the top */
    window.scrollTo(0, 0);
    for (let a = (cards[0] || root).parentElement; a; a = a.parentElement) a.scrollTop = 0;
    let S = cards[0] ? cards[0].parentElement : null;
    while (S && S !== document.body && !scrollable(S)) S = S.parentElement;
    if (!S || S === document.body || !scrollable(S)) S = se;
    document.querySelectorAll("[data-shot-scroller]").forEach((e) => e.removeAttribute("data-shot-scroller"));
    S.scrollTop = 0;
    const isWin = S === se;
    const sr = isWin ? { top: 0, bottom: innerHeight } : S.getBoundingClientRect();
    /* fixed/sticky bars across the top cover the form → start the form below them */
    let cover = sr.top;
    document.querySelectorAll("body *").forEach((el) => {
      const p = getComputedStyle(el).position;
      if (p !== "fixed" && p !== "sticky") return;
      const r = el.getBoundingClientRect();
      if (r.width > innerWidth * 0.5 && r.top <= sr.top + 5 && r.bottom > cover && r.bottom < sr.top + 300) cover = r.bottom;
    });
    const abs = (el, edge) => el.getBoundingClientRect()[edge] - sr.top + S.scrollTop;
    const visH = sr.bottom - cover;
    const offset = cover - sr.top;
    S.setAttribute("data-shot-scroller", "1");
    if (!cards.length) return { hasForm: false, isWin, start: 0, end: 0, visH, maxScroll: S.scrollHeight - S.clientHeight };
    const top = abs(cards[0], "top");
    const bottom = Math.max(...ends.map((e) => abs(e, "bottom")));
    return { hasForm: true, isWin, start: Math.max(0, top - offset - PAD), end: bottom + PAD, visH, maxScroll: S.scrollHeight - S.clientHeight };
  }, { PAD, plain });
}

async function scrollTo(pg, y) {
  await pg.evaluate((y) => {
    const S = document.querySelector("[data-shot-scroller]") || document.scrollingElement;
    S.scrollTop = y;
  }, y);
  await sleep(200);
}

/* 16:9 viewport shots from the top of the main form to its last card / action bar */
async function captureParts(pg, relBase, meta, plain) {
  const g = await formGeometry(pg, plain);
  const step = Math.max(200, g.visH - OVERLAP);
  const first = Math.min(g.start, Math.max(0, g.maxScroll));
  let count = 1;
  if (g.hasForm && g.end > first + g.visH) count = 1 + Math.ceil((g.end - (first + g.visH)) / step);
  count = Math.min(count, MAX_PARTS);
  const shots = [];
  let last = -1;
  for (let i = 0; i < count; i++) {
    const y = Math.min(first + i * step, Math.max(0, g.maxScroll));
    if (y === last) break; // reached the bottom of the scroll area
    last = y;
    await scrollTo(pg, y);
    const file = relBase + "_" + pad2(i + 1) + ".png";
    await pg.screenshot({ path: path.join(OUT, file) });
    shots.push(Object.assign({ part: i + 1, file: posix(file), thumb: posix(file.replace(/\.png$/, ".thumb.jpg")) }, meta));
  }
  if (!g.hasForm && !plain) shots.forEach((s) => { s.noForm = true; });
  return shots;
}

async function makeThumbs(tp, shots) {
  for (const s of shots) {
    const b64 = fs.readFileSync(path.join(OUT, s.file)).toString("base64");
    const dataUrl = await tp.evaluate(async ({ b64, w, h }) => {
      const img = new Image();
      img.src = "data:image/png;base64," + b64;
      await img.decode();
      const c = document.createElement("canvas");
      c.width = w; c.height = h;
      const x = c.getContext("2d");
      x.imageSmoothingQuality = "high";
      x.drawImage(img, 0, 0, w, h);
      return c.toDataURL("image/jpeg", 0.78);
    }, { b64, w: THUMB.width, h: THUMB.height });
    fs.writeFileSync(path.join(OUT, s.thumb), Buffer.from(dataUrl.split(",")[1], "base64"));
  }
}

const branchSlug = (o, gi, oi) => (/^[a-z0-9_-]{1,30}$/i.test(o.value) ? o.value : "b" + (gi + 1) + "-" + (oi + 1));

async function captureStep(pg, url, relBase, plain, errors) {
  await load(pg, url);
  let shots = await captureParts(pg, relBase, { branch: null, label: "ค่าเริ่มต้น" }, plain);
  if (plain) return shots;
  const groups = await radioGroups(pg);
  const used = new Set();
  for (let gi = 0; gi < groups.length; gi++) {
    const grp = groups[gi];
    for (let oi = 0; oi < grp.options.length; oi++) {
      const o = grp.options[oi];
      if (o.checked) continue; // shown in the default set already
      await load(pg, url);
      const clicked = await clickRadio(pg, grp.name, oi);
      if (!clicked) { errors.push("radio not found: " + grp.name + "#" + oi); continue; }
      let slug = branchSlug(o, gi, oi);
      if (used.has(slug)) slug = "b" + (gi + 1) + "-" + (oi + 1);
      used.add(slug);
      shots = shots.concat(await captureParts(pg, relBase + "__" + slug, { branch: slug, label: o.label || slug, group: grp.name }, false));
    }
  }
  return shots;
}

function writeIndexes(manifest) {
  const rows = [];
  Object.keys(manifest).sort().forEach((key) => {
    const e = manifest[key];
    (e.shots.length ? e.shots : [{}]).forEach((s) => rows.push({
      key, act: e.act, graph: e.graph || "", label: e.label || "", page: e.page, role: e.role || "", caseId: e.caseId || "",
      branch: s.branch || "", branchLabel: s.label || "", part: s.part || "", file: s.file || "", thumb: s.thumb || "",
      errors: (e.errors || []).join(" | "), capturedAt: e.capturedAt,
    }));
  });
  /* markdown */
  const md = ["# Screenshots — activity10 playthrough", "", "สร้างโดย `video/tools/capture-screens.js` · 1920×1080 · เปิดจาก `playthrough-10x.html`", "",
    "| key | ขั้น | หน้า | บทบาท | ทางเลือก | ภาพ | errors |", "|---|---|---|---|---|---|---|"];
  const cell = (s) => String(s == null ? "" : s).replace(/\|/g, "/");
  Object.keys(manifest).sort().forEach((key) => {
    const e = manifest[key];
    const byBranch = {};
    e.shots.forEach((s) => { const b = s.branch ? s.label : "ค่าเริ่มต้น"; (byBranch[b] = byBranch[b] || []).push(s); });
    const branches = Object.keys(byBranch);
    (branches.length ? branches : ["-"]).forEach((b, i) => {
      const links = (byBranch[b] || []).map((s) => "[" + pad2(s.part) + "](" + encodeURI(s.file) + ")").join(" ");
      md.push("| " + (i ? "" : "`" + key + "`") + " | " + (i ? "" : cell(e.label)) + " | " + (i ? "" : e.page) + " | " +
        (i ? "" : cell(e.role)) + " | " + cell(b) + " | " + links + " | " + (i ? "" : cell((e.errors || []).join("; "))) + " |");
    });
  });
  fs.writeFileSync(path.join(OUT, "index.md"), md.join("\n") + "\n", "utf8");
  /* xlsx via python openpyxl (no extra npm dependency) */
  const json = path.join(OUT, ".index-rows.json");
  fs.writeFileSync(json, JSON.stringify(rows), "utf8");
  try {
    execFileSync("python", [path.join(__dirname, "shots-index-xlsx.py"), json, path.join(OUT, "index.xlsx")], { stdio: "inherit" });
  } finally {
    fs.unlinkSync(json);
  }
}

async function main() {
  const filter = process.argv[2] || "";
  if (process.argv[2] === "--index") { writeIndexes(readManifest()); return; }
  fs.mkdirSync(OUT, { recursive: true });
  const manifest = filter ? readManifest() : {};
  if (!filter) {
    /* full run → clear old shots (only the folders this tool makes) */
    fs.readdirSync(OUT, { withFileTypes: true }).forEach((d) => {
      if (d.isDirectory()) fs.rmSync(path.join(OUT, d.name), { recursive: true, force: true });
    });
  }

  const browser = await launch();
  const context = await browser.newContext({ viewport: VIEWPORT, deviceScaleFactor: 1, locale: "th-TH" });
  const pt = await context.newPage();
  const tp = await context.newPage();
  let pageErrors = [];
  /* fresh tab per step: a page that leaves a pending navigation would abort every later goto */
  const freshPage = async () => {
    const p = await context.newPage();
    p.on("dialog", (d) => d.dismiss().catch(() => {}));
    p.on("pageerror", (e) => pageErrors.push("pageerror: " + String(e.message).split("\n")[0]));
    return p;
  };

  await pt.goto(fileUrl("playthrough-10x.html"), { waitUntil: "load" });
  await pt.waitForFunction(() => window.PLAYTHROUGH && window.Activity10);
  if (!filter) await pt.evaluate(() => window.Activity10.resetData && window.Activity10.resetData());
  const steps = (await pt.evaluate(() => window.PLAYTHROUGH.steps())).filter((s) => matches(s.key, filter));
  const others = filter ? OTHER_PAGES.filter((p) => matches("other." + p, filter)) : OTHER_PAGES;
  console.log("steps:", steps.length, "· other pages:", others.length);

  const t0 = Date.now();
  for (let i = 0; i < steps.length; i++) {
    const s = steps[i];
    removeShots(manifest[s.key]);
    const rel = await pt.evaluate((k) => window.PLAYTHROUGH.stepUrl(k), s.key);
    const caseId = (rel.match(/[?&]id=([^&]+)/) || [])[1];
    const errors = [];
    pageErrors = [];
    if (!caseId && !NO_CASE.test(s.page)) errors.push("no case prepared (page opened without ?id=)");
    fs.mkdirSync(path.join(OUT, s.act), { recursive: true });
    const relBase = path.join(s.act, s.nid + "_" + s.page.replace(/\.html$/, ""));
    let shots = [];
    const pg = await freshPage();
    try {
      shots = await captureStep(pg, fileUrl(rel), relBase, false, errors);
      await makeThumbs(tp, shots);
    } catch (e) {
      errors.push("capture failed: " + String(e.message).split("\n")[0]);
    }
    await pg.close().catch(() => {});
    if (shots.some((x) => x.noForm)) errors.push("no .form-card (top of page captured)");
    shots.forEach((x) => delete x.noForm);
    errors.push(...Array.from(new Set(pageErrors)));
    manifest[s.key] = {
      act: s.act, graph: s.graph, label: s.label, page: s.page, role: s.role,
      caseId: caseId ? decodeURIComponent(caseId) : null, shots, errors, capturedAt: new Date().toISOString(),
    };
    console.log(`[${i + 1}/${steps.length}] ${s.key} → ${shots.length} shot(s)${errors.length ? " ⚠ " + errors.join("; ") : ""}`);
  }

  for (const p of others) {
    const key = "other." + p;
    removeShots(manifest[key]);
    fs.mkdirSync(path.join(OUT, "other"), { recursive: true });
    const errors = [];
    pageErrors = [];
    let shots = [];
    const pg = await freshPage();
    try {
      shots = await captureStep(pg, fileUrl(p + ".html"), path.join("other", p), true, errors);
      await makeThumbs(tp, shots);
    } catch (e) {
      errors.push("capture failed: " + String(e.message).split("\n")[0]);
    }
    await pg.close().catch(() => {});
    errors.push(...Array.from(new Set(pageErrors)));
    manifest[key] = { act: "other", graph: "", label: p, page: p + ".html", role: "", caseId: null, shots, errors, capturedAt: new Date().toISOString() };
    console.log(`[other] ${p} → ${shots.length} shot(s)${errors.length ? " ⚠ " + errors.join("; ") : ""}`);
  }

  await browser.close();
  writeManifest(manifest);
  writeIndexes(manifest);
  const total = Object.values(manifest).reduce((n, e) => n + e.shots.length, 0);
  console.log(`done: ${Object.keys(manifest).length} entries, ${total} shots, ${Math.round((Date.now() - t0) / 1000)}s → ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
